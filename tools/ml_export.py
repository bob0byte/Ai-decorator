# Export the trained network into src/NeuralData.hpp (weights as float arrays + token placement table).
import sys, json, pickle
import numpy as np
P, OUTH = sys.argv[1], sys.argv[2]
meta = json.load(open(P + '/pack/ml/model_meta.json'))
W = pickle.load(open(P + '/pack/ml/ckpt.pkl', 'rb'))['W']
names = ['W1', 'B1', 'W2', 'B2', 'W3', 'B3']
with open(OUTH, 'w') as f:
    f.write('// Generated by tools/ml_export.py from the trained decoration network. Do not edit.\n#pragma once\n#include <array>\n\nnamespace nn {\n')
    f.write(f'inline constexpr int NIN = {meta["nin"]}, H1 = {meta["h1"]}, H2 = {meta["h2"]}, V = {meta["v"]}, R = {meta["R"]};\n')
    f.write('inline constexpr int NHB = %d, NTYPES = %d;\n' % (len(meta['hb']), len(meta['types'])))
    f.write('inline constexpr char const* HB[] = {%s};\n' % ', '.join('"%s"' % h for h in meta['hb']))
    f.write('inline constexpr char const* TYPES[] = {%s};\n' % ', '.join('"%s"' % t for t in meta['types']))
    for n, w in zip(names, W):
        flat = np.asarray(w, np.float32).ravel()
        f.write(f'inline constexpr float {n}[{flat.size}] = {{')
        f.write(','.join(('%.4g' % v).replace('e-0', 'e-') for v in flat))
        f.write('};\n')
    # token: id, along, out, rot, sx, sy, z, zo
    f.write('struct Token { int id; float along, out, rot, sx, sy; int z, zo; };\n')
    f.write('inline constexpr Token TOKENS[%d] = {' % len(meta['tokens']))
    f.write(','.join('{%d,%g,%g,%g,%g,%g,%d,%d}' % tuple(t) for t in meta['tokens']))
    f.write('};\n}\n')
import os; print('bytes', os.path.getsize(OUTH))
